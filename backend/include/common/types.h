#pragma once  // 防止头文件被多次包含

#include "core/game-types.h"  // 包含新的类型定义

// ============================================================================
// 物理碰撞结构体 - 碰撞检测数据 (保留向后兼容)
// ============================================================================

struct CircleCollider {
  f32 cx;                     // 圆心X坐标
  f32 cy;                     // 圆心Y坐标
  f32 r;                      // 圆的半径
};

struct BoxCollider {
  f32 x;                      // 盒子左上角X坐标
  f32 y;                      // 盒子左上角Y坐标
  f32 w;                      // 盒子宽度
  f32 h;                      // 盒子高度
};

// ============================================================================
// 碰撞结果结构体 - 碰撞检测返回结果
// ============================================================================
struct CollisionResult {
  bool collided;              // 是否发生碰撞
  f32 overlap_x;              // X轴重叠距离(分离方向)
  f32 overlap_y;              // Y轴重叠距离(分离方向)
};

// ============================================================================
// 坦克状态结构体 - 坦克属性和位置
// ============================================================================

struct TankState {
  u32 tank_id;                // 坦克唯一ID
  bool alive;                 // 坦克是否存活
  TankSide side;              // 坦克阵营(玩家/敌人)
  TankLevel level;            // 坦克等级
  i32 hp;                     // 坦克血量
  Direction direction;        // 坦克朝向
  f32 x;                      // 坦克中心X坐标
  f32 y;                      // 坦克中心Y坐标
  bool moving;                // 坦克是否移动中
  u32 born_at;                // 坦克出生时刻(毫秒)
};

// ============================================================================
// 子弹状态结构体 - 子弹属性和位置
// ============================================================================
struct BulletState {
  u32 bullet_id;              // 子弹唯一ID
  f32 x;                      // 子弹中心X坐标
  f32 y;                      // 子弹中心Y坐标
  Direction direction;        // 子弹飞行方向
  u32 tank_id;                // 发射子弹的坦克ID
  u32 fired_at;               // 子弹发射时刻(毫秒)
};

// ============================================================================
// 爆炸状态结构体 - 爆炸效果属性
// ============================================================================
struct ExplosionState {
  u32 id;                     // 爆炸效果ID
  f32 cx;                     // 爆炸中心X坐标
  f32 cy;                     // 爆炸中心Y坐标
  ExplosionShape shape;       // 爆炸效果形状
  u32 started_at;             // 爆炸开始时刻(毫秒)
};

// ============================================================================
// 道具状态结构体 - 道具属性和位置
// ============================================================================
struct PowerUpState {
  u32 id;                     // 道具唯一ID
  PowerUpName name;           // 道具类型
  f32 x;                      // 道具X坐标
  f32 y;                      // 道具Y坐标
  bool visible;               // 道具是否可见
  u32 appeared_at;            // 道具出现时刻(毫秒)
};

// ============================================================================
// 游戏常数定义 - 物理参数和尺寸
// ============================================================================

constexpr f32 BLOCK_SIZE = 16.0f;           // 一个方格的大小(像素)
constexpr f32 TANK_SIZE = 32.0f;            // 坦克尺寸(像素)
constexpr f32 BULLET_SIZE = 8.0f;           // 子弹尺寸(像素)
constexpr f32 BULLET_SPEED = 128.0f;        // 子弹速度(像素/秒)
constexpr f32 TANK_SPEED_BASIC = 64.0f;     // 基础坦克速度(像素/秒)
constexpr f32 TANK_SPEED_FAST = 96.0f;      // 快速坦克速度(像素/秒)

// ============================================================================
// 游戏循环常数 - 帧率相关参数
// ============================================================================

constexpr u32 STEP_MS = 1000 / 60;          // 单个逻辑步的毫秒数(16.67ms)
constexpr f32 STEP_SEC = STEP_MS / 1000.0f; // 单个逻辑步的秒数(0.01667s)
