#pragma once  // 防止头文件被多次包含

#include <cstdint>  // 引入标准整数类型库
#include <array>    // 引入数组模板库

// ============================================================================
// 基本类型别名 - 简化类型名称
// ============================================================================

using f32 = float;           // 32位浮点数
using i32 = int32_t;         // 32位有符号整数
using u32 = uint32_t;        // 32位无符号整数

// ============================================================================
// 方向枚举 (0=上, 1=下, 2=左, 3=右)
// ============================================================================
enum class Direction : u32 {
  UP = 0,                     // 向上方向
  DOWN = 1,                   // 向下方向
  LEFT = 2,                   // 向左方向
  RIGHT = 3,                  // 向右方向
};

// ============================================================================
// 道具类型枚举 (6种游戏道具)
// ============================================================================
enum class PowerUpName : u32 {
  TANK = 0,                   // 额外生命
  STAR = 1,                   // 攻击升级
  GRENADE = 2,                // 消灭所有敌人
  TIMER = 3,                  // 冻结所有敌人
  HELMET = 4,                 // 护盾
  SHOVEL = 5,                 // 保护老鹰
};

// ============================================================================
// 地图方格类型枚举 (7种地形)
// ============================================================================
enum class MapItemType : u32 {
  EMPTY = 0,                  // 空白
  EAGLE = 1,                  // 老鹰(保护目标)
  BRICK = 2,                  // 砖墙
  STEEL = 3,                  // 钢墙(不可摧毁)
  RIVER = 4,                  // 河流(不可通行)
  SNOW = 5,                   // 冰面(滑动加速)
  FOREST = 6,                 // 森林(隐蔽)
};

// ============================================================================
// 坦克等级枚举 (4级升级系统)
// ============================================================================
enum class TankLevel : u32 {
  BASIC = 0,                  // 基础坦克
  FAST = 1,                   // 快速坦克
  POWER = 2,                  // 火力坦克
  ARMOR = 3,                  // 装甲坦克
};

// ============================================================================
// 坦克阵营枚举 (玩家vs敌人)
// ============================================================================
enum class TankSide : u32 {
  PLAYER = 0,                 // 玩家方坦克
  BOT = 1,                    // AI敌人坦克
};

// ============================================================================
// 爆炸效果形状枚举 (5种爆炸效果)
// ============================================================================
enum class ExplosionShape : u32 {
  SMALL_0 = 0,                // 小爆炸动画第1帧
  SMALL_1 = 1,                // 小爆炸动画第2帧
  SMALL_2 = 2,                // 小爆炸动画第3帧
  BIG_0 = 3,                  // 大爆炸动画第1帧
  BIG_1 = 4,                  // 大爆炸动画第2帧
};

// ============================================================================
// 音效名称枚举 (12种游戏音效)
// ============================================================================
enum class SoundName : u32 {
  STAGE_START = 0,            // 关卡开始音效
  GAME_OVER = 1,              // 游戏结束音效
  BULLET_SHOT = 2,            // 子弹射出音效
  BULLET_HIT_1 = 3,           // 子弹击中音效1
  BULLET_HIT_2 = 4,           // 子弹击中音效2
  EXPLOSION_1 = 5,            // 爆炸音效1
  EXPLOSION_2 = 6,            // 爆炸音效2
  PAUSE = 7,                  // 暂停音效
  POWERUP_APPEAR = 8,         // 道具出现音效
  POWERUP_PICK = 9,           // 道具获取音效
  STATISTICS_1 = 10,          // 统计信息音效
  SNOW_SLIDE = 11,            // 冰面滑动音效
};

// ============================================================================
// 几何结构体 - 二维空间数据
// ============================================================================

struct Point {
  f32 x;                      // X坐标
  f32 y;                      // Y坐标
};

struct Rect {
  f32 x;                      // 矩形左上角X坐标
  f32 y;                      // 矩形左上角Y坐标
  f32 w;                      // 矩形宽度
  f32 h;                      // 矩形高度
};

// ============================================================================
// 物理碰撞结构体 - 碰撞检测数据
// ============================================================================

struct CircleCollider {
  f32 cx;                     // 圆心X坐标
  f32 cy;                     // 圆心Y坐标
  f32 r;                      // 圆的半径
};

struct BoxCollider {
  f32 x;                      // 盒子左上角X坐标
  f32 y;                      // 盒子左上角Y坐标
  f32 w;                      // 盒子宽度
  f32 h;                      // 盒子高度
};

// ============================================================================
// 碰撞结果结构体 - 碰撞检测返回结果
// ============================================================================
struct CollisionResult {
  bool collided;              // 是否发生碰撞
  f32 overlap_x;              // X轴重叠距离(分离方向)
  f32 overlap_y;              // Y轴重叠距离(分离方向)
};

// ============================================================================
// 坦克状态结构体 - 坦克属性和位置
// ============================================================================

struct TankState {
  u32 tank_id;                // 坦克唯一ID
  bool alive;                 // 坦克是否存活
  TankSide side;              // 坦克阵营(玩家/敌人)
  TankLevel level;            // 坦克等级
  i32 hp;                     // 坦克血量
  Direction direction;        // 坦克朝向
  f32 x;                      // 坦克中心X坐标
  f32 y;                      // 坦克中心Y坐标
  bool moving;                // 坦克是否移动中
  u32 born_at;                // 坦克出生时刻(毫秒)
};

// ============================================================================
// 子弹状态结构体 - 子弹属性和位置
// ============================================================================
struct BulletState {
  u32 bullet_id;              // 子弹唯一ID
  f32 x;                      // 子弹中心X坐标
  f32 y;                      // 子弹中心Y坐标
  Direction direction;        // 子弹飞行方向
  u32 tank_id;                // 发射子弹的坦克ID
  u32 fired_at;               // 子弹发射时刻(毫秒)
};

// ============================================================================
// 爆炸状态结构体 - 爆炸效果属性
// ============================================================================
struct ExplosionState {
  u32 id;                     // 爆炸效果ID
  f32 cx;                     // 爆炸中心X坐标
  f32 cy;                     // 爆炸中心Y坐标
  ExplosionShape shape;       // 爆炸效果形状
  u32 started_at;             // 爆炸开始时刻(毫秒)
};

// ============================================================================
// 道具状态结构体 - 道具属性和位置
// ============================================================================
struct PowerUpState {
  u32 id;                     // 道具唯一ID
  PowerUpName name;           // 道具类型
  f32 x;                      // 道具X坐标
  f32 y;                      // 道具Y坐标
  bool visible;               // 道具是否可见
  u32 appeared_at;            // 道具出现时刻(毫秒)
};

// ============================================================================
// 游戏常数定义 - 物理参数和尺寸
// ============================================================================

constexpr f32 BLOCK_SIZE = 16.0f;           // 一个方格的大小(像素)
constexpr f32 TANK_SIZE = 32.0f;            // 坦克尺寸(像素)
constexpr f32 BULLET_SIZE = 8.0f;           // 子弹尺寸(像素)
constexpr f32 BULLET_SPEED = 128.0f;        // 子弹速度(像素/秒)
constexpr f32 TANK_SPEED_BASIC = 64.0f;     // 基础坦克速度(像素/秒)
constexpr f32 TANK_SPEED_FAST = 96.0f;      // 快速坦克速度(像素/秒)

// ============================================================================
// 游戏循环常数 - 帧率相关参数
// ============================================================================

constexpr u32 STEP_MS = 1000 / 60;          // 单个逻辑步的毫秒数(16.67ms)
constexpr f32 STEP_SEC = STEP_MS / 1000.0f; // 单个逻辑步的秒数(0.01667s)
