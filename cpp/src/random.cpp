#include "random.h"                // 包含随机数生成器头文件

// ============================================================================
// 全局随机数生成器实例 - 供整个引擎使用
// ============================================================================

SeededRandom g_random(1);           // 创建全局随机数生成器对象,初始种子为1

// ============================================================================
// 随机数初始化函数 - C接口(供WASM绑定调用)
// ============================================================================

extern "C" {                        // 声明C链接(避免C++名称修饰)
  /**
   * 用指定的种子初始化全局随机数生成器
   * @param seed 随机数种子值
   */
  void init_random(u32 seed) {      // 定义初始化函数
    g_random = SeededRandom(seed);  // 创建新的随机数生成器对象并赋给全局变量
  }
}
